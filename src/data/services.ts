export function clusterServices(group: ServiceGroup) {
  return serviceClusters[group].map((cluster) => ({
    label: cluster.label,
    items: cluster.slugs
      .map((slug) => services.find((service) => service.slug === slug))
      .filter((service): service is Service => Boolean(service)),
  }))
}

