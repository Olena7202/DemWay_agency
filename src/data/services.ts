export const serviceGroups = [
  'Сайти',
  'Редизайн',
  'SEO',
  'Реклама',
  'Системи',
  'Айдентика',
] as const

export type ServiceGroup = (typeof serviceGroups)[number]

export const serviceGroupAnchors: Record<ServiceGroup, string> = {
  Сайти: 'sayty',
  Редизайн: 'redyzayn',
  SEO: 'seo',
  Реклама: 'reklama',
  Системи: 'systemy',
  Айдентика: 'aydentyka',
}

export function groupFromAnchor(value: string | null | undefined): ServiceGroup | undefined {
  if (!value) return
  return serviceGroups.find((group) => serviceGroupAnchors[group] === value)
}

